// Command coverage runs the backend tests and reports statement coverage of the hand-written
// code. Generated sqlc code, the entrypoint and this tool are left out, so the number reflects
// code someone could have a test for. Run it from backend/:
//
//	go run ./tools/coverage              print coverage per package and in total
//	go run ./tools/coverage -min 80      also exit 1 if the total is below 80%
//	go run ./tools/coverage -html        also write coverage.html to browse uncovered lines
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path"
	"sort"
	"strconv"
	"strings"
)

// excluded lists import path fragments that are not measured.
var excluded = []string{
	"/internal/database/dbgen", // generated by sqlc
	"/cmd/",                    // entrypoint wiring
	"/tools/",                  // this tool
	"/internal/testutil/",      // helpers for tests
}

func main() {
	min := flag.Float64("min", 0, "fail if total coverage is below this percentage")
	html := flag.Bool("html", false, "also write the HTML report to coverage.html")
	profile := flag.String("profile", "coverage.out", "where to write the coverage profile")
	flag.Parse()

	module := strings.TrimSpace(output("go", "list", "-m"))
	var measured []string
	for pkg := range strings.FieldsSeq(output("go", "list", "./...")) {
		if !isExcluded(pkg) {
			measured = append(measured, pkg)
		}
	}

	// Every package's tests run, but only the measured packages are instrumented, so a test in
	// one package counts towards the code it exercises in another.
	test := exec.Command("go", "test", "-p", "4", "./...", "-coverprofile="+*profile, "-coverpkg="+strings.Join(measured, ","))
	test.Stdout, test.Stderr = os.Stdout, os.Stderr
	if err := test.Run(); err != nil {
		fmt.Fprintln(os.Stderr, "\ntests failed, coverage not reported")
		os.Exit(1)
	}

	total, err := report(*profile, module)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if *html {
		run("go", "tool", "cover", "-html="+*profile, "-o", "coverage.html")
		fmt.Println("wrote coverage.html")
	}
	if !meetsMinimum(total, *min) {
		fmt.Fprintf(os.Stderr, "coverage %.1f%% is below the required %.1f%%\n", total, *min)
		os.Exit(1)
	}
}

// meetsMinimum reports whether total coverage satisfies the -min threshold. A threshold of 0
// accepts anything.
func meetsMinimum(total, min float64) bool { return total >= min }

func isExcluded(pkg string) bool {
	for _, e := range excluded {
		if strings.Contains(pkg+"/", e) {
			return true
		}
	}
	return false
}

type counts struct{ covered, total int }

func (c counts) percent() float64 {
	if c.total == 0 {
		return 100
	}
	return 100 * float64(c.covered) / float64(c.total)
}

// report prints coverage per package from a profile and returns the total percentage.
func report(profile, module string) (float64, error) {
	f, err := os.Open(profile)
	if err != nil {
		return 0, err
	}
	defer f.Close()

	// Each test binary writes every instrumented block, so the same block appears once per
	// package that was tested. A block counts once, and as covered if any of them ran it.
	type block struct {
		pkg   string
		stmts int
		hit   bool
	}
	blocks := map[string]*block{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "mode:") {
			continue
		}
		// "<file>:<start>,<end> <statements> <hits>"
		fields := strings.Fields(line)
		if len(fields) != 3 {
			return 0, fmt.Errorf("unexpected profile line %q", line)
		}
		colon := strings.LastIndex(fields[0], ":")
		stmts, err1 := strconv.Atoi(fields[1])
		hits, err2 := strconv.Atoi(fields[2])
		if colon < 0 || err1 != nil || err2 != nil {
			return 0, fmt.Errorf("unexpected profile line %q", line)
		}
		b := blocks[fields[0]]
		if b == nil {
			b = &block{pkg: strings.TrimPrefix(path.Dir(fields[0][:colon]), module+"/"), stmts: stmts}
			blocks[fields[0]] = b
		}
		b.hit = b.hit || hits > 0
	}
	if err := sc.Err(); err != nil {
		return 0, err
	}

	byPkg := map[string]*counts{}
	var all counts
	for _, b := range blocks {
		c := byPkg[b.pkg]
		if c == nil {
			c = &counts{}
			byPkg[b.pkg] = c
		}
		c.total += b.stmts
		all.total += b.stmts
		if b.hit {
			c.covered += b.stmts
			all.covered += b.stmts
		}
	}

	names := make([]string, 0, len(byPkg))
	for name := range byPkg {
		names = append(names, name)
	}
	sort.Slice(names, func(i, j int) bool { return byPkg[names[i]].percent() < byPkg[names[j]].percent() })

	fmt.Printf("\n%7s  %11s  %s\n", "cover", "statements", "package")
	for _, name := range names {
		c := byPkg[name]
		fmt.Printf("%6.1f%%  %5d/%-5d  %s\n", c.percent(), c.covered, c.total, name)
	}
	fmt.Printf("%6.1f%%  %5d/%-5d  total\n", all.percent(), all.covered, all.total)
	return all.percent(), nil
}

func output(name string, args ...string) string {
	out, err := exec.Command(name, args...).Output()
	if err != nil {
		fmt.Fprintf(os.Stderr, "%s %s: %v\n", name, strings.Join(args, " "), err)
		os.Exit(1)
	}
	return string(out)
}

func run(name string, args ...string) {
	cmd := exec.Command(name, args...)
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	if err := cmd.Run(); err != nil {
		fmt.Fprintf(os.Stderr, "%s %s: %v\n", name, strings.Join(args, " "), err)
		os.Exit(1)
	}
}
